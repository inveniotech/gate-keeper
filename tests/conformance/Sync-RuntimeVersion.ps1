# Generates runtime version constants from middleware/version.txt. Use -Check in CI.
[CmdletBinding()]
param([switch] $Check)
$ErrorActionPreference = 'Stop'
$repository = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$version = [IO.File]::ReadAllText((Join-Path $repository 'middleware/version.txt')).Trim()
if ($version -cnotmatch '^\d+\.\d+\.\d+$') { throw 'Supply one semantic runtime version.' }
$notice = '// Generated by tests/conformance/Sync-RuntimeVersion.ps1; do not edit.'
$outputs = @{
    'middleware/dotnet/RuntimeBuildVersion.cs' = (@($notice,
        'namespace InvenioTech.GateKeeper.Middleware;',
        "internal static class RuntimeBuildVersion { internal const string Value = `"$version`"; }", '') -join "`n")
    'middleware/node/version.ts' = (@($notice, "export const adapterVersion = '$version';", '') -join "`n")
    'middleware/jvm/src/africa/gatekeeper/BuildVersion.java' = (@($notice,
        'package africa.gatekeeper;',
        "final class BuildVersion { static final String VALUE = `"$version`"; private BuildVersion() { } }", '') -join "`n")
}
$packagePath = Join-Path $repository 'middleware/node/package.json'
$package = [IO.File]::ReadAllText($packagePath) -replace '("version"\s*:\s*")[^"]+("\s*,)', "`${1}$version`${2}"
$outputs['middleware/node/package.json'] = $package.Replace("`r`n", "`n")
foreach ($relative in $outputs.Keys) {
    $path = Join-Path $repository $relative
    if ($Check) {
        if (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path).Replace("`r`n", "`n") -cne $outputs[$relative]) {
            throw "Runtime version metadata is stale: $relative. Run tests/conformance/Sync-RuntimeVersion.ps1."
        }
    } else { [IO.File]::WriteAllText($path, $outputs[$relative], [Text.UTF8Encoding]::new($false)) }
}
Write-Output 'Runtime version metadata is consistent.'
