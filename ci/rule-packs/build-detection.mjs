import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assemblePack } from '../pack-release/assembly/build.mjs';
import { packVersion, packDate } from './detection-authoring.mjs';

/** Generates release-source content, reference pages and synthetic cases; never signs or publishes. */
export async function detectionFiles() {
  const result = new Map();
  const inventory = [];
  const sources = new URL('./rules/', import.meta.url);
  for (const file of readdirSync(sources).filter(name => name.endsWith('.mjs')).sort()) {
    const { default: source } = await import(new URL(file, sources));
    if (!source.description?.trim() || !source.limits?.trim() || !source.fix?.trim()) throw new Error('Every detection source needs reference documentation.');
    const metadata = { id: `invenio.${source.family}`, version: packVersion, provenance: 'bundled', minEngineVersion: '0.1.0',
      coverageDate: packDate, contentIssuedAt: packDate, keyId: 'unsigned-source' };
    const input = { schemaVersion: 1, ...metadata, rules: source.rules };
    delete input.keyId;
    const { content } = assemblePack([input], metadata);
    result.set(`rule-packs/${source.family}.pack.json`, content);
    for (const item of source.cases ?? []) {
      inventory.push(item);
      result.set(`tests/corpus/${item.name}/repo/${item.path}`, Buffer.from(item.text));
      result.set(`tests/corpus/${item.name}/expected.json`, Buffer.from(JSON.stringify(item.expected, null, 2) + '\n'));
    }
    const lines = [`# ${source.title}`, '', '<!-- Generated by node ci/rule-packs/build-detection.mjs --write. -->', '',
      source.description, '', `Version: \`${packVersion}\`. Source: \`rule-packs/${source.family}.pack.json\`.`, '',
      'The citation register records owner approval in principle; legal review remains pending. A finding requests review and does not establish a legal breach.', '',
      '| Rule | Severity | Citation |', '|---|---|---|', ...source.rules.map(rule => `| \`${rule.id}\` | ${rule.severity} | ${rule.citation.title} ${rule.citation.ndpa}; ${rule.citation.gaid}. |`), '',
      '## Limits', '', source.limits, '', '## Remediation and exceptions', '', source.fix, '',
      '## Synthetic examples', '', 'Positive and near-miss examples are generated from the documented synthetic values. Their expected files contain locations only.', '',
      ...(source.cases ?? []).map(item => `- [${item.name}](../../tests/corpus/${item.name}/repo/${item.path}): ${item.expected.length ? 'finding expected' : 'no finding expected'}.`), '',
      ...(source.rules.some(rule => rule.processor) ? ['## Processor metadata', '', '| Rule | Data categories | Usual region |', '|---|---|---|',
        ...source.rules.filter(rule => rule.processor).map(rule => `| \`${rule.id}\` | ${rule.processor.dataCategories.join('; ')} | ${rule.processor.usualRegion} |`), ''] : []),
      '## Verification', '', `Run \`dotnet test tests/Corpus.Tests -c Release --filter FullyQualifiedName~DetectionPackTests\` for exact locations and measured synthetic precision/recall.`, '',
      'These are unsigned release-source packs. Tests sign only in memory with the labelled development key. Production signing, embedding and publication are separate release operations; no development signature is shipped.', '',
      ...(source.sources ? ['## Technical sources', '', ...source.sources.map(url => `- ${url}`), ''] : [])];
    result.set(`docs-data/rules/${source.family}.md`, Buffer.from(lines.join('\n')));
  }
  const readmePath = new URL('../../tests/corpus/README.md', import.meta.url);
  const readme = readFileSync(readmePath, 'utf8');
  const startMarker = '<!-- generated-detection-cases:start -->';
  const endMarker = '<!-- generated-detection-cases:end -->';
  const start = readme.indexOf(startMarker);
  const end = readme.indexOf(endMarker);
  if ((start === -1) !== (end === -1) || (start !== -1 && end < start)) throw new Error('The detection inventory markers are malformed.');
  const section = [startMarker, '## Authored detection acceptance cases', '',
    'Regenerate this table with `node ci/rule-packs/build-detection.mjs --write`. Every case uses the documented synthetic generator or processor tokens without personal data.', '',
    '| Case | Expected rule |', '|---|---|', ...inventory.sort((left, right) => left.name < right.name ? -1 : left.name > right.name ? 1 : 0)
      .map(item => `| \`${item.name}\` | ${item.expected.length ? item.expected.map(entry => `\`${entry.ruleId}\``).join(', ') : 'No finding'} |`), '', endMarker].join('\n');
  const updated = start === -1 ? readme.trimEnd() + '\n\n' + section + '\n'
    : readme.slice(0, start) + section + readme.slice(end + endMarker.length);
  result.set('tests/corpus/README.md', Buffer.from(updated));
  return result;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const mode = process.argv[2];
  if (process.argv.length !== 3 || !['--write', '--check'].includes(mode)) throw new Error('Use --write or --check.');
  const root = new URL('../../', import.meta.url);
  for (const [name, bytes] of await detectionFiles()) {
    const target = fileURLToPath(new URL(name, root));
    if (mode === '--write') { mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, bytes); }
    else if (!readFileSync(target).equals(bytes)) throw new Error(`Generated detection output differs: ${name}. Regenerate it.`);
  }
  console.log('Detection source packs, reference pages and synthetic cases verified. No signing or publication occurred.');
}
