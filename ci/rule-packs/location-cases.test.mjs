import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { buildLocationCases } from '../../tests/corpus/New-LocationCases.mjs';

test('location acceptance covers every identifier in each inventory context', () => {
  const cases = buildLocationCases();
  assert.equal(cases.filter(item => item.mode === 'value').length, 25);
  for (const family of ['bvn', 'nin', 'nuban', 'phone', 'email']) {
    for (const kind of ['log', 'fixture', 'configuration', 'migration', 'api-model']) {
      const item = cases.find(entry => entry.name === `p2-location-${family}-${kind}`);
      assert.equal(item.kind, kind);
      assert.equal(item.expected.length, 1);
      assert.equal(item.expected[0].ruleId, `pii.${family}`);
    }
  }
});
test('unsafe BVN and NIN field cases cover all launch stacks without literal identifiers', () => {
  const cases = buildLocationCases().filter(item => item.mode === 'field');
  assert.equal(cases.length, 18);
  for (const item of cases) {
    assert.doesNotMatch(item.text, /\d{10,11}/);
    assert.equal(item.expected.length, 1);
    assert.match(item.expected[0].ruleId, /^pii\.(bvn|nin)\.field\.(log|migration|api)$/);
  }
});
test('committed location fixtures are regenerated byte for byte', () => {
  const script = fileURLToPath(new URL('../../tests/corpus/New-LocationCases.mjs', import.meta.url));
  const result = spawnSync(process.execPath, [script, '--check'], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
});
