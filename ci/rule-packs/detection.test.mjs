import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { detectionFiles } from './build-detection.mjs';

test('detection packs, reference pages and corpus inputs are regenerated byte for byte', async () => {
  for (const [path, bytes] of await detectionFiles()) {
    assert.deepEqual(readFileSync(new URL(`../../${path}`, import.meta.url)), bytes, path);
  }
});
