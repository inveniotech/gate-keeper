import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { buildIdentifierCases } from '../../tests/corpus/New-IdentifierCases.mjs';

test('identifier acceptance cases cover five families in all three launch languages', () => {
  const cases = buildIdentifierCases();
  assert.equal(cases.length, 25);
  for (const family of ['bvn', 'nin', 'nuban', 'phone', 'email']) {
    for (const language of ['dotnet', 'node', 'jvm']) {
      const entry = cases.find(item => item.name === `p2-${family}-${language}-source`);
      assert.equal(entry.expected.length, 1);
      assert.equal(entry.expected[0].ruleId, `pii.${family}`);
      assert.equal(entry.expected[0].line, 1);
      assert.ok(entry.expected[0].column > 1);
    }
    for (const kind of ['shape-near-miss', 'validator-near-miss']) {
      assert.deepEqual(cases.find(item => item.name === `p2-${family}-${kind}`).expected, []);
    }
  }
});
test('committed identifier fixtures are regenerated byte for byte', () => {
  const script = fileURLToPath(new URL('../../tests/corpus/New-IdentifierCases.mjs', import.meta.url));
  const result = spawnSync(process.execPath, [script, '--check'], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
});
